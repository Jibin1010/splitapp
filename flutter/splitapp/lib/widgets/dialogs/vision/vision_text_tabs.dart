import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import '../../../theme/app_theme.dart';

class VisionRawTextTab extends StatefulWidget {
  final String? rawText;

  const VisionRawTextTab({super.key, required this.rawText});

  @override
  State<VisionRawTextTab> createState() => _VisionRawTextTabState();
}

class _VisionRawTextTabState extends State<VisionRawTextTab> {
  bool _copied = false;

  @override
  Widget build(BuildContext context) {
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Row(
          mainAxisAlignment: MainAxisAlignment.spaceBetween,
          children: [
            const Text(
              'Verbatim line-by-line transcription directly from the receipt image:',
              style: TextStyle(fontSize: 11, color: AppColors.textMuted),
            ),
            OutlinedButton.icon(
              onPressed: () async {
                await Clipboard.setData(ClipboardData(text: widget.rawText ?? ''));
                setState(() => _copied = true);
                Future.delayed(const Duration(seconds: 2), () {
                  if (mounted) setState(() => _copied = false);
                });
              },
              icon: Icon(_copied ? Icons.check : Icons.copy_rounded, size: 12),
              label: Text(_copied ? 'Copied' : 'Copy Raw Text', style: const TextStyle(fontSize: 11)),
              style: OutlinedButton.styleFrom(
                padding: const EdgeInsets.symmetric(horizontal: 8, vertical: 4),
              ),
            ),
          ],
        ),
        const SizedBox(height: 8),
        Container(
          width: double.infinity,
          height: 240,
          padding: const EdgeInsets.all(12),
          decoration: BoxDecoration(
            color: const Color(0xFF090D16),
            borderRadius: BorderRadius.circular(8),
            border: Border.all(color: AppColors.border),
          ),
          child: SingleChildScrollView(
            child: SelectableText(
              widget.rawText ?? 'No raw text transcribed.',
              style: const TextStyle(
                fontFamily: 'monospace',
                fontSize: 11,
                height: 1.4,
                color: Color(0xFFE2E8F0),
              ),
            ),
          ),
        ),
      ],
    );
  }
}

